function mergeLocale(file, patch, errors, photosExtra) {
  const full = path.join(root, "messages", file);
  const data = JSON.parse(fs.readFileSync(full, "utf8"));
  Object.assign(data, patch);
  data.Wizard = data.Wizard || {};
  data.Wizard.errors = { ...(data.Wizard.errors || {}), ...errors };
  data.Wizard.photos = { ...(data.Wizard.photos || {}), ...photosExtra };
  fs.writeFileSync(full, `${JSON.stringify(data, null, 2)}\n`, "utf8");
  console.log(`Updated ${file}`);
}

